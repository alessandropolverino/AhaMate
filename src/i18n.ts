export type Lang = 'it' | 'en';
export type Params = Record<string, string | number>;
/**
 * A translatable message: analysis code emits these, the UI renders them.
 * `line` is set on the reasons that talk about the engine's line ("…the line
 * suggests…"), and holds that line as numbered SAN for the hover tooltip.
 */
export type Msg = {
  key: string;
  params?: Params;
  /** The engine's line as numbered SAN, shown on hover. */
  line?: string;
  /** The raw metric behind the sentence, kept visible so a claim stays auditable. */
  detail?: { key: string; params?: Params };
};

